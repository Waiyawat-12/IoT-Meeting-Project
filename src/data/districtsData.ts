export const DISTRICT_BY_ID: Record<string, District> = Object.fromEntries(
  DISTRICTS.map((d) => [d.id, d]),
);

export function findDistrict(idOrName: string): District | undefined {
  const key = idOrName.trim().toLowerCase();
  return DISTRICTS.find(
    (d) =>
      d.id.toLowerCase() === key ||
      d.nameEN.toLowerCase() === key ||
      d.nameTH === idOrName ||
      String(d.code) === idOrName ||
      String(d.code) === key.replace(/^th/, ""),
  );
}
